def _read_csv_files(files):
    """Read and combine one or more CSV files."""

    frames = []

    for file in sorted(files):
        try:
            frames.append(pd.read_csv(file))
        except Exception as exc:
            st.warning(
                f"Could not read {file.name}: {exc}"
            )

    if not frames:
        return None

    return pd.concat(
        frames,
        ignore_index=True
    )


@st.cache_data(show_spinner=False)
def load_spark_result(result_name):
    """
    Load a Spark result.

    Spark normally produces:

        result_name/
            part-00000-....csv
            _SUCCESS

    Ordinary CSV files are also supported.
    """

    result_path = RESULTS_DIR / result_name

    if not result_path.exists():
        return None

    # Spark output directory
    if result_path.is_dir():

        part_files = sorted(
            result_path.glob("part-*.csv")
        )

        if part_files:
            return _read_csv_files(
                part_files
            )

        csv_files = sorted(
            result_path.glob("*.csv")
        )

        if csv_files:
            return _read_csv_files(
                csv_files
            )

        return None

    # Direct CSV
    if (
        result_path.is_file()
        and result_path.suffix.lower() == ".csv"
    ):
        return _read_csv_files(
            [result_path]
        )

    return None


