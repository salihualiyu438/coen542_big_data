def number(value):
    """Format numeric values."""

    try:
        return f"{float(value):,.2f}"
    except Exception:
        return "0.00"


def first_value(
    dataframe,
    column,
    default=None
):
    """Safely retrieve first value."""

    if (
        dataframe is None
        or dataframe.empty
        or column not in dataframe.columns
    ):
        return default

    value = dataframe[column].iloc[0]

    if pd.isna(value):
        return default

    return value


def result_status(dataframe):
    """Return result availability."""

    if (
        dataframe is not None
        and not dataframe.empty
    ):
        return "Available"

    return "Not found"


